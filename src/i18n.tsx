const LangCtx = createContext<{ lang: Lang; s: Dict; setLang: (l: Lang) => void }>({ lang: 'en', s: t.en, setLang: () => {} });
export const useLang = () => useContext(LangCtx);

function readLang(): Lang {
  try { const v = localStorage.getItem('lang'); return v === 'bn' ? 'bn' : 'en'; } catch { return 'en'; }
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang);
  useEffect(() => { document.documentElement.lang = lang === 'bn' ? 'bn' : 'en'; }, [lang]);
  const setLang = (l: Lang) => { setLangState(l); try { localStorage.setItem('lang', l); } catch { /* ignore */ } };
  return <LangCtx.Provider value={{ lang, s: t[lang] as Dict, setLang }}>{children}</LangCtx.Provider>;
}

// Bengali digits for numbers shown in Bengali
export const bnDigits = (v: string | number, lang: Lang) =>
  lang === 'bn' ? String(v).replace(/[0-9]/g, (d) => '০১২৩৪৫৬৭৮৯'[Number(d)]) : String(v);
